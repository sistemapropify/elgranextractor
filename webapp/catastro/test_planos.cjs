const assert=require('node:assert/strict');
const core=require('../static/js/planos-geometry.js');
const polygon={type:'Feature',id:'original',properties:{Layer:'Lotes',codigo:'A-01',texto:'<script>literal</script>'},geometry:{type:'Polygon',coordinates:[[[-71.535,-16.4],[-71.534,-16.4],[-71.534,-16.399],[-71.535,-16.4]]]}};
const collection=feature=>({type:'FeatureCollection',features:[feature]});
const normalized=core.normalize(collection(polygon));
assert.equal(core.layerName(normalized.features[0]),'Lotes');
assert.deepEqual(normalized.features[0].properties,polygon.properties);
assert.equal(core.positions(normalized.features[0].geometry).length,4);
assert.equal(core.layerName({properties:{}}),'Sin capa');
