const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../static/js/catastro-maestro.js'),'utf8'),context);
const api=context.window.CatastroMasterGeometry;
const polygon={type:'Polygon',coordinates:[[[0,0],[4,0],[4,4],[0,4],[0,0]],[[1,1],[2,1],[2,2],[1,2],[1,1]]]};
assert.equal(api.contains(polygon,[.5,.5]),true);
assert.equal(api.contains(polygon,[1.5,1.5]),false);
assert.equal(api.contains(polygon,[5,5]),false);
const multi={type:'MultiPolygon',coordinates:[polygon.coordinates,[[[6,6],[8,6],[8,8],[6,8],[6,6]]]]};
assert.equal(api.contains(multi,[7,7]),true);
assert.equal(api.contains(multi,[5,5]),false);
const feature={id:12,properties:{ID_LOTE:null,COD_LOTE:null},geometry:polygon};
const r=api.record(feature,{id:'pdf'},'lotes');
assert.equal(r.rings.length,2);
assert.equal(r.feature.properties.ID_LOTE,null);
assert.notEqual(api.recordId({id:'pdf'},'lotes',feature),api.recordId({id:'geollaqta'},'lotes',feature));
assert.deepEqual(Array.from(api.world([0,0])),[128,128]);
console.log('Master geometry: holes, multipolygons, source namespaces and missing codes verified.');
