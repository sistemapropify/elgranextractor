const assert=require('node:assert/strict');
const api=require('../static/js/visor-planos-labels.js');
assert.deepEqual(api.world(0,0),[.5,.5]);
assert.equal(api.category('NOMBRES_URBANIZACIONES'),0);
assert.equal(api.category('NUMEROS_MANZANAS'),1);
assert.equal(api.category('NUMEROS_LOTES'),2);
const draws=[],frames=[],segments=[];
const ctx={beginPath(){},moveTo(x,y){segments.push([x,y]);},lineTo(x,y){segments.push([x,y]);},stroke(){},setTransform(){},clearRect(){draws.length=0;segments.length=0;},strokeText(){},fillText(text,x,y){draws.push({text,x,y});}};
let canvas;
global.document={createElement:()=>canvas={style:{},dataset:{},setAttribute(){},getContext:()=>ctx,remove(){}}};
global.requestAnimationFrame=fn=>{frames.push(fn);return frames.length;};global.cancelAnimationFrame=()=>{};
const zoom={value:18},center={lng:()=>-71.53,lat:()=>-16.35};
const projection={fromLatLngToDivPixel:()=>({x:0,y:0}),getWorldWidth:()=>256*2**zoom.value};
global.google={maps:{OverlayView:class{setMap(map){if(map)this.onAdd();else this.onRemove();}getProjection(){return projection;}getPanes(){return{overlayLayer:{appendChild(){}}};}}}};
const map={getCenter:()=>center,getDiv:()=>({clientWidth:1000,clientHeight:700}),getZoom:()=>zoom.value,getMapTypeId:()=> 'roadmap'};
const layer=new Map([['NUMEROS_LOTES',{visible:true,color:'#ffffff'}],['LOTES',{visible:true,color:'#808080'}]]);
const features=Array.from({length:30000},(_,i)=>({geometry:{type:'Point',coordinates:i<10?[-71.53,-16.35]:[-70,-15]},properties:{capa:'NUMEROS_LOTES',texto:String(i+1)}}));
features.push(...Array.from({length:28300},(_,i)=>{const x=i===0?-71.53:-70;const y=i===0?-16.35:-15;return {geometry:{type:'Polygon',coordinates:[[[x,y],[x+.00001,y],[x+.00001,y+.00001],[x,y]]]},properties:{capa:'LOTES'}};}));
const overlay=api.create(map);overlay.setFeatures(features,layer,.8);frames.shift()();
assert.equal(canvas.dataset.loadedLabels,'30000','Retain every loaded label, not a sample');
assert.equal(canvas.dataset.loadedContours,'28300','Retain every lot contour');
assert.equal(segments.length,4,'Draw only the visible polygon edges, without fills or circle pins');
assert.equal(overlay.pick({lng:()=>-71.53,lat:()=>-16.35}),features[30000],'Vector selection uses retained original features');
assert.equal(draws.length,10,'Paint on-screen labels as text without thousands of invisible markers');
assert.equal(draws[0].x,500);assert.equal(draws[0].y,350);
assert.equal(ctx.fillStyle,'#243444','White CAD text must remain legible on the light basemap');
zoom.value=13;overlay.draw();frames.shift()();assert.equal(draws.length,0,'Fine lot numbers wait for readable zoom without dropping data');
zoom.value=18;layer.get('NUMEROS_LOTES').visible=false;overlay.draw();frames.shift()();assert.equal(draws.length,0);
layer.get('NUMEROS_LOTES').visible=true;overlay.draw();frames.shift()();assert.equal(draws.length,10,'Labels reappear without downloading the drawing again');
console.log('Plan labels: all 30,000 retained; viewport/zoom painting, correct projection and readable text verified.');
